const assert = require('node:assert/strict');
const { normalize, excludes, override } = require('../ui/preferences.js');
const song = { id: 'one', preference: { categories: ['backing', 'solo-explicit'] } };
assert.equal(excludes(song, normalize()), false);
let settings = normalize({ enabledCategories: ['backing', 'unknown', 'backing'] });
assert.deepEqual(settings.enabledCategories, ['backing']);
assert.equal(excludes(song, settings), true);
settings = override(settings, song.id, 'keep');
assert.equal(excludes(song, settings), false);
settings = override(settings, song.id, 'exclude');
assert.equal(excludes(song, settings), true);
assert.equal(settings.keepTrackIds.length, 0);
settings = override(settings, song.id, 'default');
assert.equal(excludes(song, settings), true);
settings.enabledCategories = [];
assert.equal(excludes(song, settings), false);
assert.equal(excludes({ id: 'ordinary' }, normalize()), false);
const group = { id: 'reported', preference: { categories: ['group-named'] } };
assert.equal(excludes(group, normalize({ enabledCategories: ['solo-explicit', 'solo-named'] })), false);
assert.equal(excludes(group, normalize({ enabledCategories: ['group-named'] })), true);
assert.equal(excludes(group, override(normalize({ enabledCategories: ['group-named'] }), group.id, 'keep')), false);
console.log('Preference UI decision checks passed');
